#!/usr/bin/env bash
# First deployment on a fresh Ubuntu VM (Oracle Always Free A1 Arm or x86; any Docker host works). Idempotent: running it
# again keeps your keys, passwords and data, rebuilds the images and restarts the stack.
#
#   SITE_ADDRESS=129-80-1-2.sslip.io MODE=api  WEB_ORIGIN=https://your-app.vercel.app  bash deploy/oracle/bootstrap.sh
#   SITE_ADDRESS=129-80-1-2.sslip.io MODE=full                                         bash deploy/oracle/bootstrap.sh
#
# MODE=api   web app on Vercel; this VM serves only /api/*   (needs WEB_ORIGIN)
# MODE=full  everything on this VM (web, api, postgres, opa) behind Caddy
# It never prints a secret. Passwords go to keys/console-logins.txt (0600); read that file yourself.
set -euo pipefail
cd "$(dirname "$0")/../.."

: "${SITE_ADDRESS:?set SITE_ADDRESS (a host name that points at this VM, e.g. <ip-with-dashes>.sslip.io)}"
MODE="${MODE:-api}"
case "$MODE" in
  api) CADDYFILE=Caddyfile.api; : "${WEB_ORIGIN:?MODE=api needs WEB_ORIGIN (the Vercel URL, no trailing slash)}" ;;
  full) CADDYFILE=Caddyfile.full; WEB_ORIGIN="${WEB_ORIGIN:-https://$SITE_ADDRESS}" ;;
  *) echo "MODE must be api or full" >&2; exit 2 ;;
esac
WEB_ORIGIN="${WEB_ORIGIN%/}"

# 1. Docker (and the compose plugin)
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
fi
if ! docker info >/dev/null 2>&1; then
  # the docker group is not active in this shell yet: re-run inside it
  exec sg docker "SITE_ADDRESS='$SITE_ADDRESS' MODE='$MODE' WEB_ORIGIN='$WEB_ORIGIN' bash '$0'"
fi

# 2. Host firewall. Oracle's Ubuntu images ship iptables rules that drop everything except ssh. (The VCN security list
#    must also allow 80 and 443: see docs/DEPLOY_ORACLE_VERCEL.md.)
if command -v iptables >/dev/null 2>&1; then
  for spec in "tcp 80" "tcp 443" "udp 443"; do
    set -- $spec
    sudo iptables -C INPUT -p "$1" --dport "$2" -j ACCEPT 2>/dev/null || sudo iptables -I INPUT 1 -p "$1" --dport "$2" -j ACCEPT
  done
  if command -v netfilter-persistent >/dev/null 2>&1; then sudo netfilter-persistent save >/dev/null 2>&1 || true; fi
fi

# 3. Secrets (kept on this VM only, never in git)
umask 077
mkdir -p keys backups
if [ ! -f keys/pg_password ]; then
  python3 - <<'PY'
import secrets
open("keys/pg_password", "w").write(secrets.token_hex(24))
PY
fi
chmod 0444 keys/pg_password   # compose mounts it as a secret; the container user is not root (uid 10001)

DC=(docker compose -f docker-compose.yml -f deploy/oracle/compose.caddy.yml --env-file deploy/oracle/.env)
if [ ! -f keys/signing.key ]; then
  # The key is generated by the same image that will use it. Only the PUBLIC key is printed.
  docker build -q -f Dockerfile.api -t actionproof-api:local . >/dev/null
  docker run --rm --user 0 --entrypoint python -v "$PWD/keys:/k" actionproof-api:local scripts/gen_key.py /k/signing.key
fi
chmod 0444 keys/signing.key   # single-tenant VM; or chown it to APP_UID/APP_GID and keep 0400 (docs/RUNBOOK.md)

# 4. deploy/oracle/.env: written once; later runs only refresh the three values you pass on the command line.
ENVF=deploy/oracle/.env
if [ ! -f "$ENVF" ]; then
  cp deploy/oracle/env.example "$ENVF"
  : > keys/console-logins.txt
  for login in rev-alice rev-bob sub-user123 admin-ops; do
    var="CONSOLE_PASSWORD_$(echo "$login" | tr 'a-z-' 'A-Z_')"
    pw="$(python3 -c 'import secrets;print(secrets.token_urlsafe(18))')"
    sed -i "s|^${var}=.*|${var}=${pw}|" "$ENVF"
    echo "${login}: ${pw}" >> keys/console-logins.txt
  done
  sed -i "s|^SEED_ON_BOOT=.*|SEED_ON_BOOT=1|" "$ENVF"
fi
sed -i "s|^SITE_ADDRESS=.*|SITE_ADDRESS=${SITE_ADDRESS}|; s|^CADDYFILE=.*|CADDYFILE=${CADDYFILE}|; s|^WEB_ORIGIN=.*|WEB_ORIGIN=${WEB_ORIGIN}|; s|^NEXT_PUBLIC_SITE_URL=.*|NEXT_PUBLIC_SITE_URL=${WEB_ORIGIN}|" "$ENVF"
chmod 0600 "$ENVF" keys/console-logins.txt

# 5. Validate, build, start
"${DC[@]}" config -q
if [ "$MODE" = full ]; then SERVICES=(postgres opa init api web caddy); else SERVICES=(postgres opa init api caddy); fi
"${DC[@]}" up -d --build "${SERVICES[@]}"

# Seeding runs on the first boot only: turn it off so a restart never touches the demo data again.
if grep -q '^SEED_ON_BOOT=1' "$ENVF"; then
  echo "waiting for the API to seed the demo data ..."
  for _ in $(seq 1 60); do
    "${DC[@]}" exec -T api python docker/healthcheck.py >/dev/null 2>&1 && break || sleep 5
  done
  sed -i "s|^SEED_ON_BOOT=.*|SEED_ON_BOOT=0|" "$ENVF"
  "${DC[@]}" up -d api
fi

echo
"${DC[@]}" ps
echo
echo "Done. API health:   https://${SITE_ADDRESS}/api/health"
echo "Console logins:     keys/console-logins.txt  (this VM only; read it, do not paste it anywhere)"
echo "Next: docs/DEPLOY_ORACLE_VERCEL.md (check list, Vercel settings, backups)."
